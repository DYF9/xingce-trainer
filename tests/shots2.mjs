import { setTimeout as sleep } from 'node:timers/promises';
import { writeFileSync } from 'node:fs';
const PORT = 9333, FILE = 'file:///D:/2_code/xc/index.html';
const target = await (await fetch('http://127.0.0.1:' + PORT + '/json/new?' + encodeURIComponent(FILE), { method: 'PUT' })).json();
const ws = new WebSocket(target.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } });
await new Promise(r => ws.addEventListener('open', r));
const send = (method, params) => { const i = ++id; return new Promise(res => { pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params: params || {} })); }); };
const ev = async (expr) => { const r = await send('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true }); return r.result.result.value; };
const shot = async (n) => { const r = await send('Page.captureScreenshot', { format: 'png' }); writeFileSync('D:/2_code/xc/shots/' + n + '.png', Buffer.from(r.result.data, 'base64')); console.log('shot', n); };
await send('Runtime.enable'); await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 414, height: 896, deviceScaleFactor: 2, mobile: true });
await send('Page.navigate', { url: FILE }); await sleep(900);
await ev('document.querySelector("[data-act=\'theme\']").click()'); await sleep(300);
await shot('m9-light-home');
await ev('document.querySelector("[data-mode=\'locate\']").click()'); await sleep(350);
await ev('document.querySelectorAll("[data-fid]")[0].click()'); await sleep(120);
await shot('m10-light-locate');
await ev('document.querySelector("[data-act=\'theme\']").click()'); await sleep(250);
console.log('done'); ws.close(); process.exit(0);
